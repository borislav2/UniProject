## Какво печелите, като покажете цената

Най-голямата полза е доверието. Когато човек види цена, той разбира, че не го чака неприятна изненада, и по-лесно прави следващата стъпка. Мнозина не се обаждат на фирма, която крие цената, защото се притесняват да не ги притиснат да купят нещо скъпо.

