## Средните решения

Между двете крайности има няколко разумни пътя. Можете да покажете цена „от“, която подсказва началото на скалата, и да обясните от какво зависи крайната сума. Така посетителят получава ориентир, без да го измамите.

Можете да покажете и примерни ценови диапазони за типични случаи, например „обикновено между толкова и толкова“. Така изразявате честно, че цената варира, и пак давате представа.

Друг вариант са пакети с ясно описание на това, което включват, като всеки пакет има своята цена. Те помагат на хората да сравняват и да избират, вместо да гадаят какво получават. И накрая, ако наистина не можете да посочите число, обяснете как се формира цената и колко бързо ще отговорите на запитване, така че мълчанието да не изглежда като укриване.

