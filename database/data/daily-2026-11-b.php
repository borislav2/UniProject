Конструкторите са създадени за хора, които искат бързо да имат сайт и не искат да мислят за техника. Хостингът, сигурността и обновяванията са включени, а страниците се подреждат с влачене. Един фризьорски салон в Пловдив, който иска страница с услуги, снимки и телефон, може да стартира за няколко дни.

Цената на тази лекота е ограничението. Вие работите в рамките на това, което конструкторът позволява, а при нестандартна идея бързо стигате до стена. Сайтът живее при компанията, която го предлага, и преместването му другаде обикновено означава да го изградите наново. Месечната такса пък продължава, докато сайтът е жив.

Това не е недостатък, ако нуждите ви са прости и стабилни. Проблемът идва, когато бизнесът порасне, а сайтът остане там, където е бил. За много малки фирми, които просто искат да бъдат намерени и да се виждат прилично, конструкторът е напълно достатъчен и не бива да се срамувате от него.

## WordPress

WordPress е най-разпространената система за сайтове в света, и това е истинско предимство. Има огромен избор от готови теми и добавки, много специалисти знаят как се работи с нея, а сайтът е ваш и можете да го преместите при друг хостинг. За фирма, която иска блог, страници с услуги и възможност за бъдещо развитие, това е надеждна основа.

Срещу гъвкавостта стои грижата. WordPress и добавките към него трябва да се обновяват редовно, иначе сайтът става уязвим. Резервните копия, сигурността и скоростта също не се случват сами. Ако никой не поема това, сайтът започва да се разпада тихо, и обикновено собственикът разбира късно.

Много от лошите впечатления от WordPress всъщност са впечатления от занемарени сайтове. Добре поддържан, той е напълно достоен избор. Попитайте всеки, който го ползва, кой го обновява, и ще разберете много за това, как ще изглежда сайтът след година.

## Сайт по поръчка

Сайтът, изграден специално за вас, няма излишни неща и е направен точно по вашия процес. Той обикновено е по-бърз, защото не носи товара на десетки добавки, и позволява нещо, което шаблоните не могат, като специфична резервационна логика или необичаен вид. За бизнес с ясна идея това е голямо предимство.

Недостатъкът е зависимостта. Ако сайтът е направен така, че само един човек го разбира, а той изчезне, вие сте в трудно положение. Затова при такъв вариант питайте предварително кой притежава кода, как ще се правят промени и какво се случва, ако се разделите с изпълнителя. Добрият изпълнител ще ви отговори спокойно и ще ви го запише на хартия. Помолете и за достъп до домейна и хостинга на ваше име, защото това е най-простата защита срещу неприятни изненади.

## Как да изберете

