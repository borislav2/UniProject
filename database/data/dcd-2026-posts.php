## Какво проверява Google

Google гледа сайта „като купувач“. Търси:

- ясни контакти и данни за фирмата;
- условия за доставка и връщане;
- цени и начини на плащане;
- HTTPS.

Без ясни контакти и политики акаунтът може да бъде спрян. А данните в Merchant Center трябва да съвпадат 1:1 със сайта: име, адрес, пощенски код, телефон, адрес на сайта, доставка, връщане. Ако на сайта пише една цена за доставка, а във фийда друга, имате проблем.

## Фийдът е сърцето на Shopping

Фийдът е файл с всички ваши продукти: име, описание, цена, наличност, снимки. Google го чете и от него прави обявите. Богомилов обобщава: „В Shopping качеството на данните е по-важно от креатива.“

Какво да има в него:

- **Заглавие** от 70 до 100 знака: марка, тип, модел, материал. Не „Купа“, а „Marka Купа за куче неръждаема стомана 1,2 л“.
- **Описание** от 700 до 1000 знака.
- **Цена и наличност**, които съвпадат със сайта. Фийдът се обновява поне веднъж дневно.
- **Снимки**: минимум 500×500 px от 31.01.2027 г. Данните на Google, цитирани от Digitas Sofia, показват, че 5 и повече снимки дават 76% повече импресии и 32% повече кликове.

От същите данни: промо цената вдига CTR с 7,6%, рейтингите с 5%, а безплатната доставка добавя 2% конверсии.

Не забравяйте и марджа. Богомилов предлага да делите продуктите по печалба и да сметнете минималния ROAS като 1 ÷ марж. При 25% марж това е ROAS 4. При по-нисък ROAS рекламата не си връща разходите при този марж.

## Ами ако магазинът не е на WooCommerce или Shopify

Фийдът се прави от данните за продуктите, а те има във всеки магазин. Как точно ги вземаме (готово разширение, експорт или файл) зависи от системата. Затова първата стъпка е кратък преглед на магазина, а не избор на инструмент. Ако данните за продуктите са разхвърляни в таблици, подреждането им е по-голямата част от работата.

## Какво да направите сега

1. Прегледайте контактите, доставката, връщането и условията. Всичко да е видимо от всяка страница.
2. Подредете данните за продуктите: пълни заглавия, описания, цени и наличности.
3. Сменете малките снимки и добавете повече на продукт.
4. Добавете структурирани данни за продуктите на сайта.
5. Настройте измерване на покупките в GA4, за да знаете какво носи пари.
6. Създайте Merchant Center и потвърдете сайта си.

Нищо от това не е загубено усилие, дори Google да отложи старта. Ясните политики и добрите данни помагат и на купувача, и на другите канали.

