## Три неща, които да направите

**1. Отговорете на всеки въпрос на клиента, в текст на сайта.** Николов цитира Маркъс Шеридан от River Pools с „They ask, you answer“: хората питат за цена, проблеми, сравнения, отзиви и кое е най-доброто. Напишете цена или поне „от … €“. Направете честно сравнение. Напишете за кого не сте подходящи: така AI и човекът повече ви вярват.

**2. Накарайте и другите да говорят за вас.** Отзиви в Google, споменавания в медии, видео, форуми, магазини и сайтове за сравнение. Най-важното е данните да са едни и същи навсякъде: име, адрес, цени, работно време.

