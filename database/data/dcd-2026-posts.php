## Три възможни отговора

Когато клиентът попита AI за вас, има три варианта:

1. AI ви потвърждава и клиентът купува.
2. AI препоръчва конкурент. Николов го казва точно: „you paid for their sale“, тоест вие сте платили за чужда продажба.
3. AI не казва нищо. По думите му: „Silence = non-existence“. Мълчанието е същото като да ви няма.

Третият вариант е най-коварен, защото не го виждате в никой отчет. Няма кликване, няма отказ, просто клиент, който никога не е стигнал до вас.

## Как AI решава на кого да вярва

AI не гледа само вашия сайт. Разбива въпроса на няколко търсения, чете страниците, до които може да стигне, и сглобява това, в което източниците са съгласни. Ако на сайта цената е една, в eMAG друга, а в сайт за сравнение трета, сигналът се чупи.

Николов връща историята към PageRank от 1998 г.: „every link is a vote“, всеки линк е глас. И добавя: „Back then the vote was a link. Today it's a review, an article, a forum, a video.“ Днес гласът е отзив, статия, форум или видео.

