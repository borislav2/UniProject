## Форматите в ChatGPT

Реклами в ChatGPT се правят с продуктов фийд, с едно или няколко изображения. Подсказките за контекст не гарантират показване. Тоест това е нов канал с малко опит, не сигурна печалба.

## Какво да направите като малък бизнес

Лекторът предлага три промени: креативи (AI и реални лица), по-прости акаунти и ясни роли на каналите. И една рамка: „Новите медии допълват Google и Meta.“ Не ги заменят.

**1. Пуснете измерването, преди да пуснете нов канал.** В GA4 трябват поне събития за запитване, обаждане и покупка. Без тях не знаете какво е сработило.

**2. Дайте на всеки канал роля.** Meta и TikTok са за първото виждане, търсачките и Google профилът са за финалния избор. Не ги мерете с една и съща мярка. Канал, който показва вас на нови хора, няма да даде най-много последни кликове, но без него няма кого да убедите после.

**3. Тествайте малко и с ясна цел.** Съветът на лектора е „малък тест с ясна цел, срок и бюджет“. Например: определена сума, четири седмици и цел за брой запитвания. Ако целта не е постигната, спирате и записвате какво сте научили.

**4. Питайте клиентите.** Най-евтиният отчет е едно поле във формата: „Откъде научихте за нас?“ Така виждате и каналите, които кликовете не показват.

**5. Обяснявайте разликите в отчета.** Когато платформите показват повече поръчки, отколкото има в магазина, това не е грешка, а различен начин на броене. По-добре да го знаете предварително, отколкото да вземате решение по грешни числа.

