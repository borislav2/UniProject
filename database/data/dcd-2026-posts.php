## Тестът, който можете да направите днес

Отнема 15 минути и е безплатен:

- Отворете ChatGPT, Gemini и Perplexity.
- Попитайте като клиент: „Кой прави [вашата услуга] в [вашия град]?“, „Колко струва [вашата услуга]?“, „Има ли добри отзиви за [вашето име]?“
