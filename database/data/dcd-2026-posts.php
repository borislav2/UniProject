## Какво значи „проверка на икономиката“

Когато еуфорията мине, остава въпросът дали системата си струва. За малък бизнес сметката е проста и може да се направи на лист:

- колко време отнема задачата днес;
- колко време отнема с AI, заедно с проверката на резултата;
- колко струва инструментът на месец;
- какво струва една грешка и колко често се случва.

Ако проверката на резултата изяжда спестеното време, значи задачата не е подходяща за автоматизация. Ако грешката е скъпа, човекът трябва да одобрява всяко действие. Това е същото, което лекторът нарича решение, базирано на риска.

