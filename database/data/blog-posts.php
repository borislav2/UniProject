## 2. Броете запитванията от формата

Всяко запитване от сайта е точно измерим резултат. Колко идват на месец? Повече или по-малко са от миналата година? Ако са нула, или формата не работи, или никой не стига до нея.

## 3. Погледнете Google Business

В профила си в Google Business виждате колко хора са ви се обадили, поискали маршрут или отворили сайта ви директно от Google. Това е безплатна и много ясна статистика.

## 4. Google Search Console

Безплатен инструмент от Google, който показва за какви търсения излиза сайтът ви, колко пъти е показан и колко пъти са кликнали. Ако сайтът почти не се показва, проблемът е във видимостта. Ако се показва, но никой не кликва, проблемът е в заглавията и описанията.

## Какво означават резултатите

- **Има посещения, няма запитвания:** сайтът не убеждава или формата е трудна. Работете по съдържанието и по формата.
- **Няма посещения:** хората не ви намират. Работете по Google профила и по видимостта.
- **Има запитвания, но не от правилните хора:** текстът привлича грешната аудитория. Бъдете по-конкретни за какво сте и за кого.

