    public static function find(string $key): ?array
    {
        $template = self::all()[$key] ?? null;

        return $template ? $template + ['key' => $key] : null;
    }

    public static function label(string $key): string
    {
        return self::all()[$key]['label'] ?? self::RETIRED[$key] ?? $key;
    }

    /** Попълва {client_name} и {business} във всеки текст (тема, заглавия, абзаци, списъци). */
    public static function fill(string $text, array $data): string
    {
        return strtr($text, ['{client_name}' => (string) ($data['client_name'] ?? ''), '{business}' => (string) ($data['business'] ?? '')]);
    }

    /** Попълва {client_name} и {business} в темата. */
    public static function subject(string $subject, array $data): string
    {
        return self::fill($subject, $data);
    }

    /** Непразните редове на текста, подрязани. */
    public static function lines(?string $text): array
    {
        return array_values(array_filter(
            array_map('trim', preg_split('/\R/u', (string) $text)),
            fn ($line) => $line !== ''
        ));
    }

    /** Редовете, разделени на първото „: “ на [заглавие, текст]; ред без „: “ става [ред, '']. */
    public static function pairs(?string $text): array
    {
        return array_map(function (string $line) {
            $pos = mb_strpos($line, ': ');

            return $pos === false ? [$line, ''] : [rtrim(mb_substr($line, 0, $pos)), trim(mb_substr($line, $pos + 2))];
        }, self::lines($text));
    }

    /**
     * Полетата, наредени по групи (ключ 'group') в реда на появяване. Полета без група влизат в първата група.
     * Шаблон без групи връща една група с празно име.
     *
     * @return array<string, array<string, array>>
     */
    public static function groups(array $fields): array
    {
        $first = '';
        foreach ($fields as $field) {
            if (! empty($field['group'])) {
                $first = $field['group'];
                break;
            }
        }
        $groups = [];
        foreach ($fields as $name => $field) {
            $groups[$field['group'] ?? $first][$name] = $field;
        }

        return $groups;
    }

    /** Валидиращи правила: текст до 255 знака, дълъг текст (textarea) до 5000, датите са дати от днес нататък, линковете са http(s). */
    public static function rules(array $template): array
    {
        $rules = [];
        foreach ($template['fields'] as $name => $field) {
            $type = $field['type'] ?? 'text';
            $rules["data.$name"] = array_filter([
                ($field['required'] ?? true) ? 'required' : 'nullable',
                $type === 'date' ? 'date' : 'string',
                match ($type) { 'date' => 'after_or_equal:today', 'textarea' => 'max:5000', default => 'max:255' },
                $type === 'url' ? 'url:http,https' : null,
            ]);
        }

        return $rules;
    }

