    /** Обяснението за име на маршрут (най-дългото съвпадение на префикс) или null, когато екранът няма такова. */
    public static function forRoute(?string $name): ?array
    {
        if (! $name) {
            return null;
        }
        $best = null;
        foreach (self::MAP as $key => $entry) {
            if (($name === $key || str_starts_with($name, $key . '.')) && ($best === null || strlen($key) > strlen($best))) {
                $best = $key;
            }
        }

        return $best === null ? null : ['key' => $best] + self::MAP[$best];
    }

    /**
     * Разделите по групите на менюто (профил all) с техните обяснения, за страницата „Как работи админът“.
     * SEO таб страниците и поддържащите екрани се добавят след своя раздел.
     *
     * @return array<string, list<array{label: string, route: string, help: array}>>
     */
    public static function sections(): array
    {
        $extra = [
            'admin.seo.index' => ['admin.seo.posts', 'admin.seo.health', 'admin.seo.keywords', 'admin.seo.ai'],
            'admin.outreach.calls.index' => [],
        ];
        $labels = [
            'admin.seo.posts' => 'SEO, Статии',
            'admin.seo.health' => 'SEO, SEO здраве',
            'admin.seo.keywords' => 'SEO, Ключови думи',
            'admin.seo.ai' => 'SEO, AI споменавания',
        ];
        $out = [];
        foreach (Profiles::menu('all', true) as $group => $items) {
            foreach ($items as $item) {
                $help = self::forRoute($item['route']);
                if (! $help) {
                    continue;
                }
                $out[$group][] = ['label' => $item['label'], 'route' => $item['route'], 'help' => $help];
                foreach ($extra[$item['route']] ?? [] as $route) {
                    $out[$group][] = ['label' => $labels[$route], 'route' => $route, 'help' => self::forRoute($route)];
                }
            }
        }

        return $out;
    }
